"""Haenam event registry loader: one place for event keys, labels, magnitudes and paths (27.Haenam_sequence).

Generated by tools/cleanup/make_registry.py (cleanup phase P4, step 1).  The CSVs next to this file are the data;
regenerate them with that tool instead of editing them by hand.

    import sys, pathlib; sys.path.insert(0, str(next(p for p in pathlib.Path(__file__).resolve().parents if (p / "registry" / "haenam.py").is_file()) / "registry")); import haenam as H
    (a notebook searches from its working folder: (pathlib.Path.cwd(), *pathlib.Path.cwd().parents))
    H.key("20260822214301")   -> "20260822T2143"   (also: the DL id, the key itself, or a legacy alias such as "M31")
    H.eid("20260822T2143")    -> "20260822214301"  (the project's 14-digit id: directories, catalogue rows)
    H.label("20260822T2143")  -> "Event 11  2026-08-22  $\\mathit{M}_{\\mathrm{w}}$ 3.1"   (exactly event_ids.label)
    H.mw("20260822T2143")     -> 3.14              (the Mw that figures show; event_ids.MW_SPEC)
    H.ffi_keys()              -> the nine keys with a slip model
    H.path("20260822T2143", "sdm_tauc")            -> the final-variant table (here KS/KG + JU)
    H.path("20260822T2143", "sdm_tauc", "KSKG")    -> the KS/KG-only table
    H.path(None, "reloc_final_catalog")            -> a global product
layout.csv holds the OLD (pre-restructure) path templates until P7, so code that switches to path() reads exactly the
files it read before.  With variant=None, path() uses the event's final network set (events.csv astf / sdm / slip).
"""
import csv
import os
import re
from functools import lru_cache
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = Path(os.environ.get("HAENAM_ROOT", str(HERE.parent)))
WORKS = Path(os.environ.get("HAENAM_WORKS", "/home/msseo/works"))
MW_MATH = r"$\mathit{M}_{\mathrm{w}}$"
_TOKEN = re.compile(r"\{([A-Za-z0-9_]+)\}")


def _read(name):
    with open(HERE / name, newline="") as fh:
        return list(csv.DictReader(fh))


@lru_cache(maxsize=None)
def _events():
    return {r["key"]: r for r in _read("events.csv")}


@lru_cache(maxsize=None)
def _aliases():
    return _read("legacy_aliases.csv")


@lru_cache(maxsize=None)
def _lookup():
    m = {}
    for k, r in _events().items():
        for c in ("key", "eid", "kma_id", "dl_id"):
            if r[c]:
                m[r[c]] = k
    for a in _aliases():
        m.setdefault(a["alias"], a["key"])
    return m


@lru_cache(maxsize=None)
def _layout():
    out = {}
    for r in _read("layout.csv"):
        out.setdefault(r["product"], []).append(r)
    return out


def reload():
    """Drop the cached CSVs (after the registry was regenerated)."""
    for f in (_events, _aliases, _lookup, _layout):
        f.cache_clear()


def keys(role=None, labelled=None):
    """Registry keys in chronological order; role in {target, egf, not_processed}; labelled=True/False filters."""
    return [k for k, r in _events().items()
            if (role is None or r["role"] == role) and (labelled is None or bool(r["label"]) == labelled)]


def key(x):
    """Key of an event given its key, 14-digit id (KMA or DL), or a legacy alias.  KeyError if unknown."""
    x = str(x).strip()
    if x.startswith("haenam_") and x[7:] in _events():   # a 24-Runner key haenam_<key> (layout slip_runner_key)
        return x[7:]
    try:
        return _lookup()[x]
    except KeyError:
        raise KeyError(f"unknown Haenam event id, key or alias: {x!r}") from None


def row(k):
    """The events.csv row (a copy) of an event."""
    return dict(_events()[key(k)])


def eid(k):
    return _events()[key(k)]["eid"]


def number(k):
    """'03' for Event 03; KeyError for an unlabelled row."""
    lab = _events()[key(k)]["label"]
    if not lab:
        raise KeyError(f"{key(k)} has no paper label")
    return lab.split()[-1]


def date(k):
    kk = key(k)
    return f"{kk[:4]}-{kk[4:6]}-{kk[6:8]}"


def mw(k):
    """The Mw figures show (events.csv mw_label = event_ids.MW_SPEC); KeyError for an unlabelled row."""
    v = _events()[key(k)]["mw_label"]
    if not v:
        raise KeyError(f"{key(k)} has no Mw label")
    return float(v)


def mw1(k):
    return f"{mw(k):.1f}"


def label(k, with_date=True, math=True):
    """'Event 03  2020-05-03  Mw 3.2' (Mw in mathtext unless math=False): the event_ids.label format."""
    r = _events()[key(k)]
    if not r["label"]:
        raise KeyError(f"{r['key']} has no paper label")
    m = MW_MATH if math else "Mw"
    return f"{r['label']}  {date(k)}  {m} {mw1(k)}" if with_date else f"{r['label']}  {m} {mw1(k)}"


def ffi_keys():
    """Keys of the events with a slip model (events.csv slip != none), chronological."""
    return [k for k, r in _events().items() if r["slip"] not in ("", "none")]


def aliases(k=None, kind=None):
    """legacy_aliases.csv rows, optionally for one event and/or one kind."""
    kk = key(k) if k is not None else None
    return [dict(a) for a in _aliases() if (kk is None or a["key"] == kk) and (kind is None or a["kind"] == kind)]


def legacy_event_ids():
    """(EVENT_IDS, MW_SPEC, FFI_IDS) keyed by the 14-digit id, exactly as notebooks_2026M31/event_ids.py defines them."""
    ev = {r["eid"]: r for r in _events().values() if r["label"]}
    return ({e: r["label"].split()[-1] for e, r in ev.items()}, {e: float(r["mw_label"]) for e, r in ev.items()},
            {_events()[k]["eid"] for k in ffi_keys()})


def products(scope=None):
    return [p for p, rows in _layout().items() if scope is None or rows[0]["scope"] == scope]


def _when(cond, r):
    if not cond:
        return True
    neg = "!=" in cond
    col, vals = cond.split("!=" if neg else "=", 1)
    hit = r.get(col.strip(), "") in vals.split("|")
    return not hit if neg else hit


def _expand(template, k, want, depth):
    if depth > 8:
        raise KeyError("layout template recursion")
    r = _events()[k] if k is not None else {}
    kinds = {}
    if k is not None:
        for a in _aliases():
            if a["key"] == k:
                kinds.setdefault(a["kind"], a["alias"])

    def tok(m):
        t = m.group(1)
        if t == "ROOT":
            return str(ROOT)
        if t == "WORKS":
            return str(WORKS)
        if t in r:
            if not r[t]:
                raise KeyError(f"{k}: empty field {t}")
            return r[t]
        if t in kinds:
            return kinds[t]
        if t in _layout():
            return _path(k, t, want, depth + 1)
        raise KeyError(f"{k}: no value for {{{t}}}")
    return _TOKEN.sub(tok, template)


def _path(k, product, variant, depth):
    rows = _layout().get(product)
    if not rows:
        raise KeyError(f"unknown product {product!r}")
    if rows[0]["scope"] == "global":
        return _expand(rows[0]["template"], None, None, depth)
    if k is None:
        raise KeyError(f"{product!r} is a per-event product; give an event")
    r = _events()[k]
    an = rows[0]["analysis"]
    want = variant if variant is not None else (r[an] if an else None)
    errs = []
    for lr in rows:
        if lr["variant"] and lr["variant"] != want:
            continue
        if not _when(lr["when"], r):
            continue
        try:
            return _expand(lr["template"], k, want, depth)
        except KeyError as e:
            errs.append(str(e))
    raise KeyError(f"{product!r} undefined for {k} (variant {want!r}): {'; '.join(errs) or 'no layout row applies'}")


def path(k, product, variant=None):
    """Path (str) of a product of one event (k = key, id or alias) or, with k=None, of a global product.
    variant: 'KSKG' or 'KSKG+JU'; None = the event's final network set for that analysis."""
    return _path(key(k) if k is not None else None, product, variant, 0)


def gpath(product):
    return path(None, product)


def runner_key(k, variant=None):
    """24-Runner / pyslipinv key of an event's slip inversion (layout slip_runner_key: haenam_<key>)."""
    return path(k, "slip_runner_key", variant)


def runner_variant(rk):
    """(key, variant) of a 24-Runner key: the event and the network set ('KSKG+JU' or 'KSKG') whose slip_runner_key it is."""
    k = key(rk)
    for v in ("KSKG+JU", "KSKG"):
        try:
            if runner_key(k, v) == rk:
                return k, v
        except KeyError:
            continue
    raise KeyError(f"{rk!r} is not a 24-Runner key of {k}")
